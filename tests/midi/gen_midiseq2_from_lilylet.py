"""Lilylet -> MIDI translation via MidiSeq2BgptSelfAttn (midiseq2 variant).

midiseq2 sibling of tests/midi/gen_midi_from_lilylet.py. Conditions on a lilylet score (a
READ-ONLY prefix encoded once by the frozen lyl encoder) and autoregressively generates the
MIDI side as the self-describing **midiseq2** token language (assets/midiseq2Vocab.yaml, vocab
838), under the SAME measure-coupled windowed/block joint attention mask the Seq2CondMidiPatchy
feeder builds (build_vis). Two things differ from the basic-MIDI base:

  1. DUAL WIDTH. The joint patch frame is patch_size=64 wide; lilylet ids occupy columns
     [0, lyl_patch_size=16) (<pad> tail) and midiseq2 ids use the full 64. So the lilylet prefix
     is patchified at width 16 (fed to the frozen encoder) and LEFT-ALIGNED into the 64-wide
     joint frame, while the midi side embeds the full 64 columns — mirroring the model's forward.

  2. MEASURE-CHUNKED midiseq2 patches with a SUPERVISED terminator. A measure is one variable-
     length midiseq2 token run ending in an <eom> TOKEN (id 4), chunked into 64-wide patches
     (only the measure's LAST patch is <pad>-padded; interior patches are full 64). Unlike the
     basic path — whose event patches ended at an UNSUPERVISED <pad> (the free-run collapse in
     gen_midi_from_lilylet's docstring) — here <eom> is a real supervised token, so the model
     learns to close measures. Generation watches for <eom> (advance measure) and the whole-song
     <eos> patch ([<bos>, <eos>, ...], stop).

Full-recompute decode (NO KV cache): the joint self-attention mask is windowed, not plain causal,
and the decoder is O(T^2), so this is meant for SHORT scores.

Usage:
  python tests/midi/gen_midiseq2_from_lilylet.py --run <run_dir>          # 3 shortest .lyl
  python tests/midi/gen_midiseq2_from_lilylet.py --files a.lyl --device cuda
"""

