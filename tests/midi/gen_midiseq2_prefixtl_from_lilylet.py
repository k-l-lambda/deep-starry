"""Lilylet -> MIDI translation via MidiSeq2PrefixInTokenLevel (split-modality, lyl-in-token-level).

Split-modality sibling of tests/midi/gen_midiseq2_from_lilylet.py. Conditions on a lilylet score
and autoregressively generates the MIDI side as the self-describing **midiseq2** token language
(assets/midiseq2Vocab.yaml, vocab 582), but with a fundamentally different architecture:

  1. NO LYL ENCODER. The lilylet signal is NOT projected into a frozen encoder memory and scattered
     into a joint decoder. Instead, the raw lilylet patches (native width-16, vocab 256) are
     RE-EMBEDDED at the TOKEN-LEVEL decoder as prefix patches at NEGATIVE RoPE positions (-Kmax..-1),
     giving the within-patch token generator direct access to the relevant lilylet measures.

  2. SPLIT MODALITY. There is no joint [T,64] frame: lilylet stays at [Lp,16] and midi at [Mp,64],
     each in its own vocabulary. The patch-level decoder sees ONLY midi patches (midi-only
     windowed self-attention); the lilylet condition enters only at the token decoder as prefix.

  3. MEASURE-ID CROSS WINDOW. For each midi target patch, the lilylet patches in its cross window
     are gathered directly from measure ids (lyl_meas, midi_src, w_cross), not from a mask tensor —
     exactly as during training.

Full-recompute decode (NO KV cache): the midi self-attention decoder is windowed-causal, so this
is meant for SHORT scores. O(Mp^2) per step at the patch level + O((Kmax+P)^2) per token step.

Usage:
  python tests/midi/gen_midiseq2_prefixtl_from_lilylet.py --run <run_dir>      # 3 shortest .lyl
  python tests/midi/gen_midiseq2_prefixtl_from_lilylet.py --files a.lyl --device cuda
"""

