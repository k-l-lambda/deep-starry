'''InterleavedSeq2 — a measure-interleaved Lilylet <-> midiseq2 translation feeder.

Where Seq2Seq2's mixed mode emits one source half and one target half, this feeder cuts the crop into
MEASURE UNITS and alternates the two languages unit by unit, source first:

    <bos>? %style\n... \n  src1 <sep> tar1 <eom>  src2 <sep> tar2 <eom>  ...  srcN <sep> tarN <eom>

Every `tar <eom>` run is supervised and nothing else is: source measures, <sep>, <bos> and the style
block are context. So the model learns to translate one bar given the bar's source plus every earlier
(source, target) pair in the window, and at inference a bar is generated by appending `src <sep>` and
decoding until <eom>.

A unit is one PLAYED measure, i.e. one row of measures.json: unit i pairs MIDI played measure i with
Lilylet measure `source_measure[i]`. Repeats are therefore unrolled — a repeated Lilylet measure
reappears in the sequence once per pass, which is what keeps every unit a 1:1 pair. The direction is
chosen by `source_format` / `target_format` exactly as in Seq2Seq2; one side must be Lilylet and the
other midiseq2.

Wrappers:

    <bos>  on a crop that starts at played measure 1, at the very front (ahead of the style block).
           Measure 1's MIDI unit also carries the file header (ticks_per_beat/format_type), as in
           Seq2Seq2's head crops.
    <eos>  NEVER emitted. Each target bar closes on <eom>, and generation stops by bar count.

Inside a MIDI unit the `@measure`/`@tick` directives are dropped: the unit structure already says where
the bar starts and ends, so no in-unit <eom> exists and `source_eom` has no meaning here.

The STYLE block (the Lilylet file's leading `%<style>` lines, with `style_dropout` per line) leads the
sequence on every crop and is unsupervised, for the same reasons as in Seq2Seq2 (see `_pick_style`).

Crops are drawn in units as `head` / `tail` / `middle` by `p_head` / `p_tail`, with a per-crop length
drawn uniformly from `line_range` (which counts MEASURES here, as in Seq2Seq2's mixed mode). When the
assembled sequence exceeds `max_tokens`, whole units are trimmed — from the end, or from the front for a
tail crop so the real ending survives — down to a minimum of one unit. Unlike Seq2Seq2 nothing has to be
resampled, because interleaving makes a unit boundary a clean cut point. The one exception is a single
unit over the bound by itself: that crop is redrawn, and truncated as a last resort, so `max_tokens` is a
hard bound on every row (see `describe`).

Two on-disk layouts, chosen by `packed` (None = auto-detect, as in Seq2Seq2):

    loose    <root>/<source_dir>/**, <root>/<target_dir>/** and <root>/metadata/measures.json — the
             mixed Seq2Seq2 layout (test202608).
    packed   <root>/<XX>.zip + index.json, built by tools/midi/packInterleavedLilylet.py. Each shard
             archive holds `<midi arm>/<id>.midiseq2.txt`, `<lyl arm>/<id>.lyl` and
             `measures/<id>.json` (the played -> Lilylet source_measure list). The manifest's `layout`
             is 'interleaved' and its shard lists hold bare sample ids. Every pair was validated at
             pack time, so nothing is re-validated at init and no map is held in memory: a sample's map
             is read with its files. `source_dir` / `target_dir` are entry prefixes here, as in Seq2Seq2.

Not supported (all refused at construction): tick marks, start_jitter, transposition, 'sep'/'absolute'
positions and the encoder-decoder 'split' pack — each either needs a single source half or is undefined
over a Lilylet arm.

Batch contract:
	input_ids    LongTensor [B, T]   the interleaved sequence, right-padded with <pad>
	masks        LongTensor [B, T]   1 = real token
	target_mask  LongTensor [B, T]   1 = a supervised position: every target-bar token and its <eom>
	position_ids LongTensor [B, T]   0..T-1 ('flat'); pad continues the run

Loss convention is Seq2Seq2's: compare `logits[:, i - 1]` against `input_ids[:, i]` wherever
target_mask is 1, so MidiTranslator / MidiTranslatorLoss consume this batch unchanged.
'''

import json
import os
import random
from typing import Any, Dict, List, Optional, Tuple

import torch
from torch.nn.utils.rnn import pad_sequence

from ...utils.parsers import parseFilterStr
from ...utils.registry import register_dataset
from .seq2seq2 import Seq2Seq2, _ZipSource, _format, _line_range, _shard_interleave


@register_dataset
class InterleavedSeq2 (Seq2Seq2):
	'''Measure-interleaved Lilylet <-> midiseq2 feeder. See the module docstring for the batch contract.

	Subclasses Seq2Seq2 to share its mixed-mode machinery — pair discovery and measures.json validation
	(`_init_mixed`), Lilylet document splitting, style dropout, MIDI measure slicing and the unified-vocab
	encoders — but NOT its constructor or crop/assembly path, which are built around one source half.
	'''

	# Packed layout: the per-sample measure-map entry prefix, and each format's file suffix.
	MEASURES_ARM = 'measures'
	SUFFIX = {'lilylet': '.lyl', 'midiseq2': '.midiseq2.txt'}

	def __init__ (self, root, split, device='cpu', shuffle=False,
		source_format='midiseq2', target_format='lilylet', source_dir='midi-seq2', target_dir='lyl',
		measures_path=None, vocab_path=None, line_range=(4, 16), p_head=0.15, p_tail=0.15,
		max_tokens=0, style_dropout=0.0, random_crop=None, seed=0, pos_style='flat', pack='flat',
		resample_tries=8, mark_mode='measure', start_jitter=0, transposition_sigma=0, packed=None, **_):
		# Dataset.__init__ only: Seq2Seq2's constructor sets up a single-half pipeline this class replaces.
		super(Seq2Seq2, self).__init__()
		self.device = device
		self.shuffle = shuffle
		self.source_format = _format(source_format)
		self.target_format = _format(target_format)
		if {self.source_format, self.target_format} != {'lilylet', 'midiseq2'}:
			raise ValueError('InterleavedSeq2 translates between lilylet and midiseq2; '
				f'got {self.source_format} -> {self.target_format}')
		self.mixed = True
		if pos_style != 'flat':
			raise ValueError('InterleavedSeq2 supports pos_style="flat" only: there is no single <sep> '
				'to anchor "sep"/"absolute" on')
		if pack != 'flat':
			raise ValueError('InterleavedSeq2 supports pack="flat" only: the halves are interleaved, '
				'so there is no source tensor to hand an encoder')
		self.pos_style = pos_style
		self.pack = pack
		# Seq2Seq2 options with no interleaved meaning. Named here rather than left to `**_`, so a config
		# carried over from Seq2Seq2 fails loudly instead of silently training without them.
		if mark_mode != 'measure':
			raise ValueError('InterleavedSeq2 units are played measures; mark_mode must be "measure"')
		if start_jitter or transposition_sigma:
			raise ValueError('start_jitter and transposition_sigma are not defined over a Lilylet arm')
		# In MEASURES (units), as in Seq2Seq2's mixed mode.
		self.line_range = _line_range(line_range)
		self.p_head = p_head
		self.p_tail = p_tail
		self.max_tokens = max_tokens
		self.resample_tries = resample_tries
		if not 0 <= style_dropout <= 1:
			raise ValueError(f'style_dropout must be in [0, 1], got {style_dropout!r}')
		self.style_dropout = float(style_dropout)
		self.random_crop = shuffle if random_crop is None else random_crop
		self.seed = seed
		self._split = split

		from .unifiedSeq2Tokenizer import UnifiedSeq2Tokenizer
		from ...lilylet.data.patchifier import LilyletTokenizer
		if not vocab_path:
			raise ValueError('InterleavedSeq2 requires a run-local unified vocab_path')
		self.tokenizer = UnifiedSeq2Tokenizer(vocab_path)
		self.lilylet_tokenizer = LilyletTokenizer(self._lilylet_asset())
		self.packed = _ZipSource.detect(root) if packed is None else bool(packed)
		self._last_map: Tuple[Optional[str], List[int]] = (None, [])
		if self.packed:
			self._init_packed(root, source_dir, target_dir)
		else:
			self._init_mixed(root, source_dir, target_dir, measures_path)

		phases, cycle = parseFilterStr(split)
		self.indices = [i for i in range(len(self.names)) if i % cycle in phases]
		if self.shuffle:
			# Once and seeded, for the reason Seq2Seq2.__init__ gives: `__iter__` never runs under the
			# DataLoader, and the order must agree across ranks and a resume. Shard-aware when packed, for
			# the read locality `_shard_interleave` describes.
			rng = random.Random(self.seed)
			if self.packed:
				self.indices = _shard_interleave(self.indices,
					lambda i: self.source.shard_of(self.names[i]), rng, self.SHUFFLE_WINDOW)
			else:
				rng.shuffle(self.indices)

	def _init_packed (self, root: str, source_dir: str, target_dir: str) -> None:
		'''Open a packTool archive set. Names come from the manifest alone; see the module docstring.'''
		self.source = _ZipSource(root)
		manifest = self.source._manifest
		if manifest is None or manifest.get('layout') != 'interleaved':
			raise ValueError(f'{root!r} is not an interleaved Lilylet package (index.json layout != '
				'"interleaved"); build one with tools/midi/packInterleavedLilylet.py')
		self._arms = {self.source_format: source_dir, self.target_format: target_dir}
		missing = [arm for arm in (source_dir, target_dir, self.MEASURES_ARM) if arm not in manifest['arms']]
		if missing:
			# Checked here because a wrong prefix would otherwise surface only as a KeyError on the first read.
			raise ValueError(f'arms {missing} not in the package; it holds {manifest["arms"]}')
		self.names = sorted(self.source.names(None))
		if not self.names:
			raise RuntimeError(f'no samples in {self.source.describe()}')

	def _mixed_mapping (self, sample_id: str) -> List[int]:
		if not self.packed:
			return super()._mixed_mapping(sample_id)
		# One describe() asks for the same map three times; keep the last one rather than re-read it.
		if self._last_map[0] != sample_id:
			self._last_map = (sample_id,
				json.loads(self.source.read(self.MEASURES_ARM, sample_id + '.json')))
		return self._last_map[1]

	def _mixed_text (self, kind: str, sample_id: str) -> str:
		if not self.packed:
			return super()._mixed_text(kind, sample_id)
		return self.source.read(self._arms[kind], sample_id + self.SUFFIX[kind])

	@staticmethod
	def _lilylet_asset () -> str:
		return os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(
			os.path.abspath(__file__))))), 'assets', 'lilylet-tokenizer.json')

	# --- crop -----------------------------------------------------------------------------

	def _pick_units (self, count: int, rng: random.Random) -> Tuple[int, int, str]:
		'''(a, z, mode): played measures a+1..z, drawn like Seq2Seq2._mixed_pick but reporting the mode,
		which `_trim` needs to know which end to cut.'''
		maximum = min(count, max(1, self.line_range[1]))
		minimum = min(maximum, self.line_range[0])
		length = minimum if minimum == maximum else rng.randint(minimum, maximum)
		roll = rng.random()
		if roll < self.p_head:
			return 0, length, 'head'
		if roll < self.p_head + self.p_tail:
			return count - length, count, 'tail'
		start = rng.randrange(0, count - length + 1)
		return start, start + length, 'middle'

	def _trim (self, units: List[Tuple[List[int], List[int]]], fixed: int, from_front: bool) -> int:
		'''How many units to drop so the sequence fits `max_tokens`, keeping at least one.

		`fixed` is the length that does not depend on the unit count (<bos> and the style block). A
		unit costs len(src) + 1 (<sep>) + len(tgt) + 1 (<eom>). Dropping from the front loses <bos> too,
		which the caller re-derives from the surviving range.
		'''
		if not self.max_tokens:
			return 0
		costs = [len(src) + len(tgt) + 2 for src, tgt in units]
		total = fixed + sum(costs)
		order = range(len(costs)) if from_front else range(len(costs) - 1, -1, -1)
		dropped = 0
		for i in order:
			if total <= self.max_tokens or dropped == len(costs) - 1:
				break
			total -= costs[i]
			dropped += 1
		return dropped

	# --- item -----------------------------------------------------------------------------

	def _encode_unit (self, played: int, lyl: List[str], midi, mapping: List[int]) -> Tuple[List[int], List[int]]:
		'''(source ids, target ids) of one played measure, both without wrappers.'''
		midi_ids = self._mixed_encode_midi(self._mixed_midi_text(midi, [played]), False)
		lyl_ids = self._mixed_encode_lilylet(lyl[mapping[played - 1] - 1])
		return (lyl_ids, midi_ids) if self.source_format == 'lilylet' else (midi_ids, lyl_ids)

	def describe (self, index: int) -> Dict[str, Any]:
		'''The whole crop decision for one sample, ids and supervision included.

		Keys: name, a, z (played-measure range a+1..z after trimming), mode, trimmed (units dropped for
		max_tokens), attempts (crops drawn, see below), truncated (ids cut by the last-resort cap), head,
		tail, style (style-block token count), played (played measure numbers), source_measures (the
		Lilylet measure of each unit), ids, target_mask (0/1 per id), units ([(start, sep, end)] id indices
		of each COMPLETE unit: src at start..sep-1, <sep> at sep, tar..<eom> at sep+1..end-1).

		`max_tokens` is a HARD bound on the row. Unit trimming stops at one unit, and one unit can exceed
		the bound on its own — measured on nota1m, 0.061% of units cost over 2048 tokens and the longest
		8,076. Such a unit survives trimming whenever it opens the crop, and one such row pads its whole
		batch to its length: that OOMed the first nota1m run at epoch 2 (21.6 G allocated against a 10.8 G
		worst case at 2048). So a crop still over the bound after trimming is REDRAWN, up to
		`resample_tries` times off the same rng (a deterministic crop stays deterministic); if every draw
		fails, the last one is truncated to `max_tokens` and reported in `truncated`. The cut unit keeps its
		supervised prefix but loses its <eom>, and is left out of `units`.
		'''
		rng = random if self.random_crop else random.Random(self.seed ^ (index * 2654435761))
		sample_id = self.names[index]
		mapping = self._mixed_mapping(sample_id)
		style_lines, lyl = self._mixed_lilylet_document(sample_id)
		midi = self._mixed_midi(sample_id)
		style = self._pick_style(index, style_lines)
		count = len(mapping)

		for attempt in range(1, max(1, self.resample_tries) + 1):
			a, z, mode = self._pick_units(count, rng)
			units = [self._encode_unit(n, lyl, midi, mapping) for n in range(a + 1, z + 1)]
			# <bos> may be lost to a front trim, so `fixed` counts it only when it could survive; a head
			# crop trims from the back and keeps it.
			from_front = mode == 'tail' and a > 0
			dropped = self._trim(units, len(style) + (1 if a == 0 else 0), from_front)
			if dropped:
				if from_front:
					units, a = units[dropped:], a + dropped
				else:
					units, z = units[:-dropped], z - dropped
			cost = (1 if a == 0 else 0) + len(style) + sum(len(src) + len(tgt) + 2 for src, tgt in units)
			if not self.max_tokens or cost <= self.max_tokens:
				break

		head = a == 0
		ids: List[int] = [self.tokenizer.bos_id] if head else []
		ids += style
		mask = [0] * len(ids)
		spans: List[Tuple[int, int, int]] = []
		for src, tgt in units:
			start = len(ids)
			ids += src + [self.tokenizer.sep_id]
			mask += [0] * (len(src) + 1)
			sep = len(ids) - 1
			ids += tgt + [self.tokenizer.eom_id]
			mask += [1] * (len(tgt) + 1)
			spans.append((start, sep, len(ids)))

		truncated = 0
		if self.max_tokens and len(ids) > self.max_tokens:
			truncated = len(ids) - self.max_tokens
			ids, mask = ids[:self.max_tokens], mask[:self.max_tokens]
			spans = [span for span in spans if span[2] <= self.max_tokens]

		played = list(range(a + 1, z + 1))
		return dict(name=sample_id, a=a, z=z, mode=mode, trimmed=dropped, attempts=attempt,
			truncated=truncated, head=head, tail=z >= count, style=len(style), played=played,
			source_measures=[mapping[n - 1] for n in played], ids=ids, target_mask=mask, units=spans)

	def _item (self, index: int) -> Tuple[torch.Tensor, torch.Tensor]:
		case = self.describe(index)
		return (torch.tensor(case['ids'], dtype=torch.long),
			torch.tensor(case['target_mask'], dtype=torch.long))

	def collateBatch (self, batch):
		sequences = [ids for ids, _ in batch]
		input_ids = pad_sequence(sequences, batch_first=True, padding_value=self.tokenizer.pad_id)
		masks = pad_sequence(
			[torch.ones(len(ids), dtype=torch.long) for ids in sequences], batch_first=True, padding_value=0)
		target_mask = pad_sequence([mask for _, mask in batch], batch_first=True, padding_value=0)
		position_ids = torch.arange(input_ids.shape[1]).unsqueeze(0).expand_as(input_ids).contiguous()

		return dict(
			input_ids=input_ids.to(self.device),
			masks=masks.to(self.device),
			target_mask=target_mask.to(self.device),
			position_ids=position_ids.to(self.device),
		)
